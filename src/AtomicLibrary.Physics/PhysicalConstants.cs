namespace AtomicLibrary.Physics;

/// <summary>Contains physical constants used in atomic physics calculations.</summary>
public static class PhysicalConstants
{
	/// <summary>The atomic mass unit (u) is defined as one twelfth of the mass of a carbon-12 atom, which is approximately 1.66053906660 × 10^-27 kilograms.</summary>
	public const double AtomicMassUnit = 1.66053906660e-27;

	/// <summary>The mass of an electron is approximately 9.1093837015 × 10^-31 kilograms.</summary>
	public const double ElectronMass = 9.1093837015e-31;

	/// <summary>The mass of a proton is approximately 1.67262192369 × 10^-27 kilograms.</summary>
	public const double ProtonMass = 1.67262192369e-27;

	/// <summary>The mass of a neutron is approximately 1.67492749804 × 10^-27 kilograms.</summary>
	public const double NeutronMass = 1.67492749804e-27;

	/// <summary>The elementary charge is approximately 1.602176634 × 10^-19 coulombs.</summary>
	public const double ElementaryCharge = 1.602176634e-19;

	/// <summary>The speed of light in a vacuum is exactly 299,792,458 meters per second.</summary>
	public const double SpeedOfLight = 299792458.0;

	/// <summary>The Planck constant is approximately 6.62607015 × 10^-34 joule seconds.</summary>
	public const double PlanckConstant = 6.62607015e-34;

	/// <summary>The Avogadro constant is approximately 6.02214076 × 10^23 mol^-1.</summary>
	public const double AvogadroConstant = 6.02214076e23;
}
